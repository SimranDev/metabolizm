const path = require('node:path');
const fs = require('node:fs/promises');
const { withDangerousMod } = require('expo/config-plugins');

/**
 * Shrink the Android bottom tab bar from Material 3's default 80dp to 64dp.
 *
 * `NativeTabs` renders react-native-screens' `TabsContainer`, which builds a
 * `BottomNavigationView` against a **hardcoded** `Theme.Material3.DayNight`
 * context wrapper — not the app's theme. So `bottomNavigationStyle` in our own
 * styles.xml is never consulted, and there is no JS prop for height: the bar
 * measures `wrap_content` over `Widget.Material3.BottomNavigationView`, whose
 * `android:minHeight` is `@dimen/m3_bottom_nav_min_height` (80dp) and whose
 * item stack is 12dp + 32dp indicator + 4dp gap + ~16dp label + 16dp = 80dp.
 *
 * The one lever left is AGP resource merging: a dimension declared in the app
 * module overrides the AAR's value of the same name. Both the floor and the
 * content stack are re-stated below so they land on the same number regardless
 * of which one dominates the measure pass:
 *
 *     6dp + 32dp indicator + 4dp gap + ~16dp label + 6dp = 64dp
 *
 * 64dp is Material's own labeled-bar height, and each item still clears the
 * 48dp minimum touch target. The system gesture/navigation inset is added by
 * `NavigationBarView` on top of this, so the bar still sits above the gesture
 * bar — only the chrome shrinks.
 *
 * Coupled to Material's resource names (verified against 1.13.0). If a future
 * version renames them these become inert extra resources and the bar quietly
 * returns to 80dp — visible, but not a build failure.
 *
 * There is no iOS equivalent: `UITabBar` owns its own height.
 */
const DIMENS = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/with-tab-bar-density.js — do not edit by hand. -->
<resources>
  <!-- Overrides com.google.android.material: 80dp / 12dp / 16dp. -->
  <dimen name="m3_bottom_nav_min_height">64dp</dimen>
  <dimen name="m3_bottom_nav_item_padding_top">6dp</dimen>
  <dimen name="m3_bottom_nav_item_padding_bottom">6dp</dimen>
</resources>
`;

module.exports = function withTabBarDensity(config) {
  return withDangerousMod(config, [
    'android',
    async (cfg) => {
      const valuesDir = path.join(
        cfg.modRequest.platformProjectRoot,
        'app/src/main/res/values',
      );
      await fs.mkdir(valuesDir, { recursive: true });
      await fs.writeFile(path.join(valuesDir, 'dimens.xml'), DIMENS);
      return cfg;
    },
  ]);
};
